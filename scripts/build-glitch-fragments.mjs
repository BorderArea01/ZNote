// Static SVG alpha masks: connected material rather than repeating scanlines.
// Fixed seeds keep screenshots stable; no runtime canvas or frame timers.
import {writeFile} from 'node:fs/promises';
function edge(seed, {mirror=false, texture=false, compact=false}={}) {
  let state=seed>>>0;
  const random=()=>((state=(Math.imul(state,1664525)+1013904223)>>>0)/4294967296);
  const height=compact?64:384, width=48, rects=[];
  for(let y=0;y<height;) {
    const h=Math.min(height-y,1+Math.floor(random()*(compact?4:6)));
    const burst=Math.pow(Math.sin(y/height*Math.PI*3.4+seed),6);
    const boundary=Math.round(16+(random()-.52)*(10+burst*44));
    if(texture) {
      if(random()<.25+burst*.65) {
        const x=Math.max(0,boundary-Math.floor(random()*10));
        rects.push(`<rect x="${x}" y="${y}" width="${Math.ceil(4+random()*(12+burst*19))}" height="${Math.min(h,1+Math.floor(random()*3))}" opacity="${(.38+random()*.62).toFixed(2)}"/>`);
      }
      if(burst>.35&&random()>.64)rects.push(`<rect x="${Math.floor(random()*10)}" y="${y}" width="${2+Math.floor(random()*8)}" height="1"/>`);
    } else {
      rects.push(`<rect x="${Math.max(0,boundary)}" y="${y}" width="${width-Math.max(0,boundary)}" height="${h}"/>`);
      if(burst>.4&&random()>.68)rects.push(`<rect x="${Math.floor(random()*8)}" y="${y}" width="${2+Math.floor(random()*7)}" height="1"/>`);
    }
    y+=h;
  }
  return `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" preserveAspectRatio="none"><g fill="white"${mirror?' transform="translate(48 0) scale(-1 1)"':''}>${rects.join('')}</g></svg>`)}")`;
}
const variables={
  'edge-left':edge(34), 'edge-right':edge(81,{mirror:true}),
  'edge-left-alt':edge(113), 'edge-right-alt':edge(57,{mirror:true}),
  'grain-left':edge(34,{texture:true}), 'grain-right':edge(81,{texture:true,mirror:true}),
  'control-left':edge(73,{compact:true}), 'control-right':edge(29,{compact:true,mirror:true}),
};
await writeFile('public/themes/glitch/fragment-masks.css',`/* Generated by scripts/build-glitch-fragments.mjs. */\nhtml[data-style="glitch"] {\n${Object.entries(variables).map(([k,v])=>`  --${k}: ${v};`).join('\n')}\n}\n`);
console.log('Built eight bounded, deterministic material masks.');
